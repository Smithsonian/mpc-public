"""
Regenerate the valid ADES JSON files and Markdown tables from the API.
"""
import json
import logging
from datetime import datetime
from pathlib import Path
from typing import Any

import requests

# Set logging level and format.
LOG_FORMAT = '%(asctime)s - %(filename)s - %(levelname)s - %(message)s'
logging.basicConfig(level=logging.INFO, format=LOG_FORMAT)

write_files = True
static_files_dir = (
        Path(__file__).parent.parent / "docs" / "mpc-ops-docs"
        / "observations" / "static"
)


def main():
    make_static_files('catalog-codes')
    make_static_files('mag-bands', {'band': 'all'}, method='GET')


def make_static_files(
        basename: str,
        payload: dict[str, Any] = {},
        method: str = 'POST'
):
    if basename == 'mag-bands':
        api_endpoint = 'mag-band'
    else:
        api_endpoint = basename
    response = requests.request(
        method=method,
        url=f"https://data.minorplanetcenter.net/api/{api_endpoint}",
        json=payload
    )
    response.raise_for_status()

    all_codes = response.json()['response']

    write_json_file(all_codes, f'{basename}.json')
    write_markdown_table(all_codes, f'{basename}.md')


def write_markdown_table(rows: list[dict[str, Any]], filename: str):
    """
    Write a list of dictionaries to a Markdown table.
    """
    if write_files:
        with open(static_files_dir / filename, "w") as f:
            f.write(
                f"[//]: # (NB: The table below is automatically generated by "
                f"`mpc-public/docs-public/scripts/generate_valid_ades_values.py`.)\n"
            )
            if 'catalog-codes' in filename:
                f.write("| ADES Code | MPC1992 Code | Catalog | Deprecated |\n")
                f.write("|-----------|----------------------|---------|------------|\n")
                for row in rows:
                    f.write(
                        f"| `{row.get('ades_code', "")}` "
                        f"| `{row.get('obs80_code')}` "
                        f"| {row.get('catalog')} "
                        f"| {row.get('deprecated')} |\n"
                    )
            elif 'mag-bands' in filename:
                f.write("| Code | Band | Allowed | Deprecated |\n")
                f.write("|------|------|---------|------------|\n")
                for row in rows:
                    f.write(
                        f"| `{row.get('band', "")}` "
                        f"| {row.get('notes')} "
                        f"| {row.get('allowed')} "
                        f"| `{row.get('deprecated', '')}` |\n"
                    )

            f.write(
                "\n"
                "!!! note\n"
                f"    This table was automatically generated on "
                f"{datetime.now().strftime('%Y-%m-%d')} "
                f"from the relevant API endpoint at "
            )
            if 'catalog-codes' in filename:
                f.write("[`/api/catalog-codes`](/docs/mpc-ops-docs/apis/catalog-codes.md). ")
            elif 'mag-bands' in filename:
                f.write("[`/api/mag-band`](/docs/mpc-ops-docs/apis/mag-band.md). ")

            f.write("Please use the API for the most recent values.\n")

        logging.info(f"Wrote Markdown table to {static_files_dir}")
    else:
        logging.info(f"Would write {len(rows)} catalog codes to {path}.")


def write_json_file(rows: list[dict[str, Any]], filename: str):
    """
    Write a list of dictionaries to a JSON file.
    """
    if write_files:
        with open(static_files_dir / filename, "w") as f:
            json.dump(rows, f, indent=2)
        logging.info(f"Wrote JSON to {static_files_dir}")
    else:
        logging.info(f"Would write {len(rows)} catalog codes to {path}.")


if __name__ == "__main__":
    main()
