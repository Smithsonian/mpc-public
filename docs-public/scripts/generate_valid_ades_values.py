"""
Regenerate the valid ADES JSON files and Markdown tables from the API.
"""
import json
import logging
from pathlib import Path
from typing import Any

import requests

# Set logging level and format.
LOG_FORMAT = '%(asctime)s - %(filename)s - %(levelname)s - %(message)s'
logging.basicConfig(level=logging.INFO, format=LOG_FORMAT)

write_files = True
static_files_dir = (
        Path(__file__).parent.parent / "docs" / "mpc-ops-docs"
        / "observations" / "static"
)


def main():
    response = requests.post(
        "https://data.minorplanetcenter.net/api/catalog-codes",
        json={}
    )
    response.raise_for_status()

    all_codes = response.json()['response']

    write_json_file(all_codes, 'catalog-codes.json')
    write_markdown_table(all_codes, 'catalog-codes.md')


def write_markdown_table(rows: list[dict[str, Any]], filename: str):
    """
    Write a list of dictionaries to a Markdown table.
    """
    if write_files:
        with open(static_files_dir / filename, "w") as f:
            f.write(
                f"[//]: # (NB: The table below is automatically generated by "
                f"`mpc-public/docs-public/scripts/generate_valid_ades_values.py`.)\n"
            )
            f.write("| ADES Code | MPC1992 Code | Catalog | Deprecated |\n")
            f.write("|-----------|----------------------|---------|------------|\n")
            for row in rows:
                f.write(
                    f"| `{row.get('ades_code', "")}` "
                    f"| `{row.get('obs80_code')}` "
                    f"| {row.get('catalog')} "
                    f"| `{row.get('deprecated')}` |\n"
                )
        logging.info(f"Wrote Markdown table to {static_files_dir}")
    else:
        logging.info(f"Would write {len(rows)} catalog codes to {path}.")


def write_json_file(rows: list[dict[str, Any]], filename: str):
    """
    Write a list of dictionaries to a JSON file.
    """
    if write_files:
        with open(static_files_dir / filename, "w") as f:
            json.dump(rows, f, indent=2)
        logging.info(f"Wrote JSON to {static_files_dir}")
    else:
        logging.info(f"Would write {len(rows)} catalog codes to {path}.")


if __name__ == "__main__":
    main()
